/** Small synchronous evidence subset for reviewed existing GeoHub page links. */
import { readFile, writeFile } from 'node:fs/promises';
import { NATIVE_PLACE_SOURCE_LINKS } from '../src/lib/nativePlaceSourceLinks.js';

const folder = new URL('../public/place-data/',import.meta.url);
const manifest = JSON.parse(await readFile(new URL('manifest.json',folder),'utf8'));
const lookup = JSON.parse(await readFile(new URL(manifest.lookup.file,folder),'utf8'));
const shards = new Map();
const records = {};
for (const id of new Set(Object.values(NATIVE_PLACE_SOURCE_LINKS))) {
  const key = lookup[id], shard = manifest.shards.find(item=>item.key===key);
  if (!shard) throw new Error(`Reviewed source link is missing: ${id}`);
  if (!shards.has(key)) shards.set(key,JSON.parse(await readFile(new URL(shard.file,folder),'utf8')));
  const record = shards.get(key).find(item=>item.id===id);
  if (!record) throw new Error(`Source record is missing: ${id}`);
  records[id] = {...record,raw:{...record.raw,source:record.raw.source || 'openstreetmap',sourceDate:manifest.source.sourceDate,attribution:manifest.attribution,attributionUrl:manifest.attributionUrl}};
}
const output = new URL('../src/lib/nativePlaceSourceRecords.generated.js',import.meta.url);
await writeFile(output,`// Generated by tools/generate-native-place-source-records.mjs; reviewed links only.\nexport const NATIVE_PLACE_SOURCE_RECORDS = ${JSON.stringify(records,null,2)};\n`);
console.log(JSON.stringify({links:Object.keys(NATIVE_PLACE_SOURCE_LINKS).length,sourceRecords:Object.keys(records).length}));
